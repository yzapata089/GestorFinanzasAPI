CREATE TABLE IF NOT EXISTS public.dispositivo (
    id_dispositivo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificador VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.categoria (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    color VARCHAR(30),
    icono VARCHAR(80),
    personalizada BOOLEAN NOT NULL DEFAULT FALSE,
    id_dispositivo INTEGER NOT NULL,
    CONSTRAINT fk_categoria_dispositivo
        FOREIGN KEY (id_dispositivo)
        REFERENCES public.dispositivo (id_dispositivo)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT uq_categoria_nombre_dispositivo
        UNIQUE (id_dispositivo, nombre),
    CONSTRAINT ck_categoria_tipo
        CHECK (LOWER(tipo) IN ('ingreso', 'gasto', 'ambos'))
);

CREATE TABLE IF NOT EXISTS public.movimiento (
    id_movimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria INTEGER NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    monto NUMERIC(14,2) NOT NULL,
    fecha DATE NOT NULL,
    descripcion VARCHAR(500) NOT NULL,
    creado TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_dispositivo INTEGER NOT NULL,
    CONSTRAINT fk_movimiento_categoria
        FOREIGN KEY (id_categoria)
        REFERENCES public.categoria (id_categoria)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT fk_movimiento_dispositivo
        FOREIGN KEY (id_dispositivo)
        REFERENCES public.dispositivo (id_dispositivo)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT ck_movimiento_monto CHECK  (LOWER(tipo) IN ('ingreso', 'gasto'))
);

CREATE TABLE IF NOT EXISTS public.presupuesto (
    id_presupuesto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria INTEGER NOT NULL,
    monto NUMERIC(14,2) NOT NULL,
    periodo VARCHAR(50) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    id_dispositivo INTEGER NOT NULL,
    CONSTRAINT fk_presupuesto_categoria
        FOREIGN KEY (id_categoria)
        REFERENCES public.categoria (id_categoria)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT fk_presupuesto_dispositivo
        FOREIGN KEY (id_dispositivo)
        REFERENCES public.dispositivo (id_dispositivo)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT ck_presupuesto_monto CHECK (monto > 0),
    CONSTRAINT ck_presupuesto_fechas CHECK (fecha_fin >= fecha_inicio)
);

CREATE TABLE IF NOT EXISTS public.abono (
    id_abono INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_presupuesto INTEGER NOT NULL,
    monto NUMERIC(14,2) NOT NULL,
    fecha DATE NOT NULL,
    descripcion VARCHAR(500) NOT NULL,
    CONSTRAINT fk_abono_presupuesto
        FOREIGN KEY (id_presupuesto)
        REFERENCES public.presupuesto (id_presupuesto)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT ck_abono_monto CHECK (monto > 0)
);

CREATE TABLE IF NOT EXISTS public.configuracion (
    id_configuracion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    moneda VARCHAR(10) NOT NULL DEFAULT 'COP',
    tema VARCHAR(30) NOT NULL DEFAULT 'claro',
    idioma VARCHAR(10) NOT NULL DEFAULT 'es',
    id_dispositivo INTEGER NOT NULL UNIQUE,
    CONSTRAINT fk_configuracion_dispositivo
        FOREIGN KEY (id_dispositivo)
        REFERENCES public.dispositivo (id_dispositivo)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

-- Índices para las consultas más frecuentes.
CREATE INDEX IF NOT EXISTS ix_categoria_dispositivo
    ON public.categoria (id_dispositivo);

CREATE INDEX IF NOT EXISTS ix_movimiento_dispositivo_fecha
    ON public.movimiento (id_dispositivo, fecha DESC);

CREATE INDEX IF NOT EXISTS ix_movimiento_dispositivo_tipo_fecha
    ON public.movimiento (id_dispositivo, tipo, fecha DESC);

CREATE INDEX IF NOT EXISTS ix_movimiento_categoria
    ON public.movimiento (id_categoria);

CREATE INDEX IF NOT EXISTS ix_presupuesto_dispositivo_fechas
    ON public.presupuesto (id_dispositivo, fecha_inicio, fecha_fin);

CREATE INDEX IF NOT EXISTS ix_presupuesto_categoria
    ON public.presupuesto (id_categoria);

CREATE INDEX IF NOT EXISTS ix_abono_presupuesto_fecha
    ON public.abono (id_presupuesto, fecha DESC);

COMMIT;

